QString defaultOutputFileForSource(const QString& sourceFile, const QString& outputDir)
{
    if (QFileInfo(QDir(outputDir).absolutePath()).dir().dirName()
            == QStringLiteral("generations")) {
        return projectOutputFile(outputDir);
    }
    const QFileInfo sourceInfo(sourceFile);
    return QDir(outputDir).absoluteFilePath(sourceInfo.completeBaseName() + QStringLiteral(".code"));
}

QString projectOutputFile(const QString& outputDir)
{
    return QDir(outputDir).absoluteFilePath(QStringLiteral("main.code"));
}

QString outputSidecarFileForSource(const QString& sourceFile,
                                   const QString& outputDir,
                                   const QString& suffix)
{
    const QFileInfo sourceInfo(sourceFile);
    const QString baseName = QFileInfo(QDir(outputDir).absolutePath()).dir().dirName()
            == QStringLiteral("generations")
            ? QStringLiteral("main")
            : sourceInfo.completeBaseName();
    return QDir(outputDir).absoluteFilePath(baseName + suffix);
}

QStringList buildCompilerProcessArgs(const QString& entryScript,
                                     const QString& compilerInputFile,
                                     const QString& outputFile)
{
    return QStringList()
            << entryScript
            << QDir::toNativeSeparators(compilerInputFile)
            << QStringLiteral("-o")
            << QDir::toNativeSeparators(outputFile)
            << QStringLiteral("-v");
}

bool prependCodeMetadataHeader(const QString& outputFile,
                               const QString& sourceFile,
                               const QString& projectName,
                               const QString& compilerInputFile,
                               QString* errorMessage)
{
    QFile file(outputFile);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        if (errorMessage) {
            *errorMessage = QStringLiteral("Failed to read generated .code file: %1").arg(outputFile);
        }
        return false;
    }
    const QByteArray body = file.readAll();
    file.close();

    const QFileInfo sourceInfo(sourceFile);
    const QFileInfo outputInfo(outputFile);
    const QFileInfo compilerInputInfo(compilerInputFile);
    QStringList header;
    header << QStringLiteral("// Generated by LH compiler integration")
           << QStringLiteral("// GeneratedAt: %1").arg(QDateTime::currentDateTime().toString(Qt::ISODate))
           << QStringLiteral("// Project: %1").arg(projectName.isEmpty() ? QStringLiteral("-") : projectName)
           << QStringLiteral("// Source: %1").arg(QDir::toNativeSeparators(sourceInfo.fileName()))
           << QStringLiteral("// CompilerInput: %1").arg(QDir::toNativeSeparators(compilerInputInfo.fileName()))
           << QStringLiteral("// Output: %1").arg(QDir::toNativeSeparators(outputInfo.fileName()))
           << QStringLiteral("// Format: .lh -> .code")
           << QString();

    QSaveFile atomicFile(outputFile);
    if (!atomicFile.open(QIODevice::WriteOnly | QIODevice::Text)) {
        if (errorMessage) {
            *errorMessage = QStringLiteral("Failed to write generated .code metadata header: %1").arg(outputFile);
        }
        return false;
    }
    const QByteArray output = header.join(QLatin1Char('\n')).toUtf8() + body;
    if (atomicFile.write(output) != output.size() || !atomicFile.commit()) {
        if (errorMessage) {
            *errorMessage = QStringLiteral("Failed to commit generated .code metadata header: %1")
                    .arg(outputFile);
        }
        return false;
    }
    return QFileInfo::exists(outputFile);
}

QString sha256ForFile(const QString& filePath)
{
    QFile file(filePath);
    if (!file.open(QIODevice::ReadOnly)) {
        return QString();
    }
    QCryptographicHash hash(QCryptographicHash::Sha256);
    hash.addData(&file);
    return QString::fromLatin1(hash.result().toHex());
}

QString runDslCompilerProcess(const QString& python,
                              const QString& entryScript,
                              const QString& compilerInputFile,
                              const QString& outputFile,
                              const QString& workDir,
                              QString* compilerStdout,
                              QString* compilerStderr)
{
    const QStringList args = buildCompilerProcessArgs(entryScript, compilerInputFile, outputFile);

    QProcess proc;
    proc.setProgram(python);
    proc.setArguments(args);
    proc.setWorkingDirectory(workDir);

    qInfo() << "[DSLCompilerInterface] Running:" << python << args
            << "cwd =" << workDir;

    proc.start();
    if (!proc.waitForFinished(120 * 1000)) {
        proc.kill();
        if (compilerStderr) {
            *compilerStderr = QStringLiteral("DSL compile process timeout.");
        }
        qWarning() << "[DSLCompilerInterface] compile process timeout.";
        return QStringLiteral("timeout");
    }

    const QString stdOut =
            TextEncoding::decodeUtf8WithLocalFallback(proc.readAllStandardOutput());
    const QString stdErr =
            TextEncoding::decodeUtf8WithLocalFallback(proc.readAllStandardError());

    if (compilerStdout) {
        *compilerStdout = stdOut;
    }
    if (compilerStderr) {
        *compilerStderr = stdErr;
    }

    if (proc.exitStatus() == QProcess::NormalExit
            && proc.exitCode() == 0
            && QFileInfo::exists(outputFile)) {
        return QString();
    }

    return QStringLiteral("exitCode=%1 outputFile=%2")
            .arg(proc.exitCode())
            .arg(outputFile);
}

