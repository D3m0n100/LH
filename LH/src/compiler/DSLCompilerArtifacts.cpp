bool validateProjectScriptPath(const QString& projectPath,
                               const QString& path,
                               QString* errorMessage)
{
    const QString trimmed = path.trimmed();
    if (trimmed.isEmpty()) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目脚本路径不能为空。");
        return false;
    }
    if (QFileInfo(trimmed).isRelative() && hasParentTraversal(trimmed)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目脚本路径禁止包含 '..'：%1").arg(path);
        return false;
    }

    const QString root = QFileInfo(projectPath).canonicalFilePath();
    const QString absolute = QFileInfo(QFileInfo(trimmed).isRelative()
                                           ? QDir(projectPath).absoluteFilePath(trimmed)
                                           : trimmed).absoluteFilePath();
    if (root.isEmpty() || !pathWithinRoot(root, absolute)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目脚本路径越出项目根目录：%1").arg(path);
        return false;
    }

    const QFileInfo candidate(absolute);
    if (candidate.exists()) {
        const QString canonical = candidate.canonicalFilePath();
        if (canonical.isEmpty() || !pathWithinRoot(root, canonical)) {
            if (errorMessage)
                *errorMessage = QStringLiteral("项目脚本符号链接越出项目根目录：%1").arg(path);
            return false;
        }
    } else {
        QDir parent = candidate.dir();
        while (!parent.exists()) {
            const QString currentPath = parent.absolutePath();
            const QDir nextParent = QFileInfo(currentPath).dir();
            if (nextParent.absolutePath() == currentPath)
                break;
            parent = nextParent;
        }
        const QString canonicalParent = parent.canonicalPath();
        if (canonicalParent.isEmpty() || !pathWithinRoot(root, canonicalParent)) {
            if (errorMessage)
                *errorMessage = QStringLiteral("项目脚本父目录越出项目根目录：%1").arg(path);
            return false;
        }
    }
    return true;
}

QString createProjectGeneration(const QString& projectPath,
                                const ProjectRuntimeConfig& config,
                                const QString& baseOutputDir,
                                QString* generationId,
                                QString* errorMessage)
{
    if (projectPath.trimmed().isEmpty() || baseOutputDir.trimmed().isEmpty()) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目发布目录不能为空。");
        return QString();
    }

    const QString root = QFileInfo(projectPath).canonicalFilePath();
    if (root.isEmpty()) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目根目录无法解析：%1").arg(projectPath);
        return QString();
    }

    const QString absoluteBaseOutputDir = QFileInfo(baseOutputDir).isRelative()
            ? QDir(root).absoluteFilePath(baseOutputDir)
            : QFileInfo(baseOutputDir).absoluteFilePath();
    QString outputPathError;
    if (!validateProjectScriptPath(root, absoluteBaseOutputDir, &outputPathError)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("项目编译输出目录无效：%1").arg(outputPathError);
        return QString();
    }

    const QString profile = profileSourcePath(root, config);
    QString pathError;
    if (!validateProjectScriptPath(root, profile, &pathError)) {
        if (errorMessage)
            *errorMessage = profile.isEmpty()
                    ? QStringLiteral("未配置有效下载 Profile，已阻止正式发布。")
                    : pathError;
        return QString();
    }
    const QFileInfo profileInfo(QFileInfo(profile).absoluteFilePath());
    if (!profileInfo.exists() || !profileInfo.isFile() || !profileInfo.isReadable()) {
        if (errorMessage)
            *errorMessage = QStringLiteral("下载 Profile 不存在或不可读：%1").arg(profile);
        return QString();
    }

    QFile profileFile(profile);
    if (!profileFile.open(QIODevice::ReadOnly)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("无法读取下载 Profile：%1").arg(profile);
        return QString();
    }
    const QByteArray profileBytes = profileFile.readAll();
    if (!validateProfileJson(profileBytes, errorMessage))
        return QString();

    const QString id = QUuid::createUuid().toString(QUuid::WithoutBraces);
    const QString generationDir = QDir(absoluteBaseOutputDir).absoluteFilePath(
            QStringLiteral("generations/%1").arg(id));
    if (!validateProjectScriptPath(root, generationDir, &outputPathError)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("generation 输出目录无效：%1").arg(outputPathError);
        return QString();
    }
    if (!QDir().mkpath(generationDir)) {
        if (errorMessage)
            *errorMessage = QStringLiteral("无法创建编译 generation：%1").arg(generationDir);
        return QString();
    }

    const QString generationProfile = QDir(generationDir).filePath(QStringLiteral("download_profile.json"));
    if (!copyFileAtomically(profile, generationProfile, errorMessage))
        return QString();
    if (generationId)
        *generationId = id;
    return generationDir;
}

