CompileResult DSLCompilerInterface::buildCompileResult(const QString& sourceFile,
                                                       const QString& outputDir,
                                                       const QString& projectName,
                                                       const QString& mainScriptFile,
                                                       const QStringList& scriptFiles,
                                                       bool success,
                                                       const QString& stdOut,
                                                       const QString& stdErr) const
{
    CompileResult result;
    result.success = success;
    result.projectName = projectName;
    result.stdOut = stdOut;
    result.stdErr = stdErr;

    if (!stdErr.trimmed().isEmpty() && !success) {
        result.errors = stdErr.split(QRegularExpression(QStringLiteral("[\r\n]+")),
                                     Qt::SkipEmptyParts);
    }

    const QString outputFile = DSLCompilerInternal::defaultOutputFileForSource(sourceFile, outputDir);
    if (QFileInfo::exists(outputFile)) {
        CompileArtifact artifact;
        artifact.type = QStringLiteral("download");
        artifact.path = outputFile;
        artifact.format = QStringLiteral("dsl_custom");
        artifact.checksum = DSLCompilerInternal::sha256ForFile(outputFile);
        artifact.metadata.insert(QStringLiteral("sourceFile"), sourceFile);
        artifact.metadata.insert(QStringLiteral("mainScriptFile"), mainScriptFile.isEmpty() ? sourceFile : mainScriptFile);
        artifact.metadata.insert(QStringLiteral("scriptFiles"), scriptFiles);
        artifact.metadata.insert(QStringLiteral("artifactScope"), QStringLiteral("project"));
        artifact.metadata.insert(QStringLiteral("outputDir"), outputDir);
        result.artifacts.append(artifact);
    }

    auto appendSidecarArtifact = [&](const QString& suffix,
                                     const QString& type,
                                     const QString& format) {
        const QString path = DSLCompilerInternal::outputSidecarFileForSource(sourceFile, outputDir, suffix);
        if (!QFileInfo::exists(path)) {
            return;
        }
        CompileArtifact artifact;
        artifact.type = type;
        artifact.path = path;
        artifact.format = format;
        artifact.checksum = DSLCompilerInternal::sha256ForFile(path);
        artifact.metadata.insert(QStringLiteral("sourceFile"), sourceFile);
        artifact.metadata.insert(QStringLiteral("mainScriptFile"), mainScriptFile.isEmpty() ? sourceFile : mainScriptFile);
        artifact.metadata.insert(QStringLiteral("scriptFiles"), scriptFiles);
        artifact.metadata.insert(QStringLiteral("artifactScope"), QStringLiteral("project"));
        artifact.metadata.insert(QStringLiteral("outputDir"), outputDir);
        result.artifacts.append(artifact);
    };

    appendSidecarArtifact(QStringLiteral(".list"),
                          QString::fromLatin1(CompileArtifactType::ParameterInitials),
                          QStringLiteral("lh_parameter_initials"));
    appendSidecarArtifact(QStringLiteral(".typ"),
                          QString::fromLatin1(CompileArtifactType::ParameterLayout),
                          QStringLiteral("lh_parameter_layout"));
    appendSidecarArtifact(QStringLiteral(".rep"),
                          QString::fromLatin1(CompileArtifactType::CompileReport),
                          QStringLiteral("lh_compile_report"));

    return result;
}

CompileResult DSLCompilerInterface::buildCompileResult(const QString& sourceFile,
                                                       const QString& outputDir,
                                                       const QString& projectName,
                                                       const QString& mainScriptFile,
                                                       const QStringList& scriptFiles,
                                                       bool success,
                                                       const QString& stdOut,
                                                       const QString& stdErr,
                                                       const ProjectRuntimeConfig& config) const
{
    return buildCompileResult(sourceFile,
                              outputDir,
                              projectName,
                              mainScriptFile,
                              scriptFiles,
                              success,
                              stdOut,
                              stdErr,
                              config,
                              QFileInfo(mainScriptFile).absolutePath(),
                              generationIdForDirectory(outputDir));
}

CompileResult DSLCompilerInterface::buildCompileResult(const QString& sourceFile,
                                                       const QString& outputDir,
                                                       const QString& projectName,
                                                       const QString& mainScriptFile,
                                                       const QStringList& scriptFiles,
                                                       bool success,
                                                       const QString& stdOut,
                                                       const QString& stdErr,
                                                       const ProjectRuntimeConfig& config,
                                                       const QString& projectPath,
                                                       const QString& generationId) const
{
    CompileResult result = buildCompileResult(sourceFile,
                                              outputDir,
                                              projectName,
                                              mainScriptFile,
                                              scriptFiles,
                                              success,
                                              stdOut,
                                              stdErr);
    result.generationId = generationId;
    result.metadata.insert(QStringLiteral("generationId"), generationId);
    result.metadata.insert(QStringLiteral("generationDirectory"),
                           DSLCompilerInternal::projectRelativePath(projectPath, outputDir));

    const QString profileSource = DSLCompilerInternal::profileSourcePath(projectPath, config);
    const QString profileSourceRelative =
            DSLCompilerInternal::projectRelativePath(projectPath, profileSource);
    if (!profileSourceRelative.isEmpty() && isSafeManifestRelativePath(profileSourceRelative)) {
        result.metadata.insert(QStringLiteral("downloadProfileSourcePath"), profileSourceRelative);
    }

    for (CompileArtifact& artifact : result.artifacts) {
        sanitizeProjectArtifactMetadata(artifact,
                                        projectPath,
                                        outputDir,
                                        mainScriptFile,
                                        scriptFiles,
                                        generationId);
    }

    if (!result.success)
        return result;

    const QString codePath = DSLCompilerInternal::projectOutputFile(outputDir);
    if (!QFileInfo::exists(codePath) || !QFileInfo(codePath).isFile()
            || DSLCompilerInternal::sha256ForFile(codePath).isEmpty()) {
        result.success = false;
        result.errors.append(QStringLiteral("generation 缺少有效 main.code，已阻止发布。"));
        return result;
    }

    const auto appendRequiredArtifact = [&](const QString& path,
                                            const QString& type,
                                            const QString& format,
                                            const QString& error) {
        if (!QFileInfo::exists(path) || !QFileInfo(path).isFile()) {
            result.success = false;
            result.errors.append(error);
            return;
        }
        CompileArtifact artifact;
        artifact.type = type;
        artifact.path = path;
        artifact.format = format;
        artifact.checksum = DSLCompilerInternal::sha256ForFile(path);
        if (artifact.checksum.isEmpty()) {
            result.success = false;
            result.errors.append(error + QStringLiteral("（无法计算 checksum）"));
            return;
        }
        sanitizeProjectArtifactMetadata(artifact,
                                        projectPath,
                                        outputDir,
                                        mainScriptFile,
                                        scriptFiles,
                                        generationId);
        result.artifacts.append(artifact);
    };

    appendRequiredArtifact(QDir(outputDir).filePath(QStringLiteral("download_profile.json")),
                           QStringLiteral("download_profile"),
                           QStringLiteral("json"),
                           QStringLiteral("generation 缺少 download_profile.json，已阻止发布。"));

    CompileArtifact pointsArtifact = generateRuntimePointsJson(outputDir, config);
    if (pointsArtifact.path.isEmpty()) {
        result.success = false;
        result.errors.append(QStringLiteral("无法生成 runtime_points.json，已阻止发布。"));
    } else {
        sanitizeProjectArtifactMetadata(pointsArtifact,
                                        projectPath,
                                        outputDir,
                                        mainScriptFile,
                                        scriptFiles,
                                        generationId);
        result.artifacts.append(pointsArtifact);
    }

    const auto points = RuntimePointConverter::fromProjectConfig(config);
    int parameterCount = 0;
    for (const auto& pt : points) {
        if (pt.kind == RuntimePointKind::Parameter)
            ++parameterCount;
    }

    if (!result.success)
        return result;

    CompileArtifact manifestArtifact = generateRuntimeManifestJson(
        outputDir,
        projectPath,
        projectName,
        mainScriptFile,
        scriptFiles,
        points.size(),
        parameterCount);
    if (manifestArtifact.path.isEmpty()) {
        result.success = false;
        result.errors.append(QStringLiteral("无法提交或校验 runtime_manifest.json，已阻止发布。"));
        return result;
    }
    sanitizeProjectArtifactMetadata(manifestArtifact,
                                    projectPath,
                                    outputDir,
                                    mainScriptFile,
                                    scriptFiles,
                                    generationId);
    result.artifacts.append(manifestArtifact);
    result.metadata.insert(QStringLiteral("runtimeManifestPath"),
                           DSLCompilerInternal::projectRelativePath(projectPath, manifestArtifact.path));
    result.metadata.insert(QStringLiteral("downloadProfilePath"),
                           DSLCompilerInternal::projectRelativePath(
                               projectPath,
                               QDir(outputDir).filePath(QStringLiteral("download_profile.json"))));
    result.metadata.insert(QStringLiteral("runtimePointsPath"),
                           DSLCompilerInternal::projectRelativePath(
                               projectPath,
                               QDir(outputDir).filePath(QStringLiteral("runtime_points.json"))));
    return result;
}

CompileArtifact DSLCompilerInterface::generateRuntimePointsJson(
    const QString& outputDir, const ProjectRuntimeConfig& config) const
{
    const auto points = RuntimePointConverter::fromProjectConfig(config);

    QJsonArray arr;
    for (const auto& pt : points) {
        QJsonObject obj;
        obj[QStringLiteral("id")] = pt.id;
        obj[QStringLiteral("name")] = pt.name;

        QString kindStr;
        switch (pt.kind) {
        case RuntimePointKind::Variable:  kindStr = QStringLiteral("Variable");  break;
        case RuntimePointKind::Parameter: kindStr = QStringLiteral("Parameter"); break;
        case RuntimePointKind::Status:    kindStr = QStringLiteral("Status");    break;
        case RuntimePointKind::Alarm:     kindStr = QStringLiteral("Alarm");     break;
        case RuntimePointKind::Resource:  kindStr = QStringLiteral("Resource");  break;
        }
        obj[QStringLiteral("kind")] = kindStr;
        obj[QStringLiteral("dataType")] = pt.dataType;
        obj[QStringLiteral("unit")] = pt.unit;

        QString accessStr;
        switch (pt.access) {
        case RuntimePointAccess::ReadOnly:  accessStr = QStringLiteral("ReadOnly");  break;
        case RuntimePointAccess::WriteOnly: accessStr = QStringLiteral("WriteOnly"); break;
        case RuntimePointAccess::ReadWrite: accessStr = QStringLiteral("ReadWrite"); break;
        }
        obj[QStringLiteral("access")] = accessStr;
        obj[QStringLiteral("sourceModule")] = pt.sourceModule;
        obj[QStringLiteral("bindingPath")] = pt.bindingPath;
        if (!pt.addressing.isEmpty())
            obj[QStringLiteral("addressing")] = QJsonObject::fromVariantMap(pt.addressing);
        if (!pt.defaultValue.isNull())
            obj[QStringLiteral("defaultValue")] = QJsonValue::fromVariant(pt.defaultValue);
        if (!pt.metadata.isEmpty())
            obj[QStringLiteral("metadata")] = QJsonObject::fromVariantMap(pt.metadata);

        arr.append(obj);
    }

    const QString filePath = QDir(outputDir).absoluteFilePath(
        QStringLiteral("runtime_points.json"));
    QSaveFile file(filePath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        qWarning() << "[DSLCompilerInterface] Failed to write" << filePath;
        return {};
    }
    const QByteArray json = QJsonDocument(arr).toJson(QJsonDocument::Indented);
    if (file.write(json) != json.size() || !file.commit()) {
        qWarning() << "[DSLCompilerInterface] Failed to commit" << filePath;
        return {};
    }

    CompileArtifact artifact;
    artifact.type = QString::fromLatin1(CompileArtifactType::RuntimePoints);
    artifact.path = filePath;
    artifact.format = QStringLiteral("json");
    artifact.checksum = DSLCompilerInternal::sha256ForFile(filePath);
    artifact.metadata.insert(QStringLiteral("pointCount"), arr.size());
    return artifact;
}

CompileArtifact DSLCompilerInterface::generateRuntimeManifestJson(
    const QString& outputDir,
    const QString& projectPath,
    const QString& projectName,
    const QString& mainScriptFile,
    const QStringList& scriptFiles,
    int pointCount,
    int parameterCount) const
{
    QJsonObject manifest;
    const QString generationId = generationIdForDirectory(outputDir);
    const QString codeFile = DSLCompilerInternal::projectOutputFile(outputDir);
    const QString profileFile = QDir(outputDir).filePath(QStringLiteral("download_profile.json"));
    const QString pointsFile = QDir(outputDir).filePath(QStringLiteral("runtime_points.json"));
    manifest[QStringLiteral("generationId")] = generationId;
    manifest[QStringLiteral("complete")] = false;
    manifest[QStringLiteral("projectName")] = projectName;
    manifest[QStringLiteral("mainScriptPath")] =
            DSLCompilerInternal::projectRelativePath(projectPath, mainScriptFile);
    manifest[QStringLiteral("dslScriptPath")] =
            DSLCompilerInternal::projectRelativePath(projectPath, mainScriptFile);

    QJsonArray scriptsArr;
    for (const auto& s : scriptFiles)
        scriptsArr.append(DSLCompilerInternal::projectRelativePath(projectPath, s));
    manifest[QStringLiteral("scriptFiles")] = scriptsArr;

    QJsonObject sourcePaths;
    sourcePaths[QStringLiteral("mainScriptPath")] =
            DSLCompilerInternal::projectRelativePath(projectPath, mainScriptFile);
    sourcePaths[QStringLiteral("dslScriptPath")] =
            DSLCompilerInternal::projectRelativePath(projectPath, mainScriptFile);
    manifest[QStringLiteral("sourcePaths")] = sourcePaths;
    manifest[QStringLiteral("sourceFileCount")] = scriptFiles.size();
    manifest[QStringLiteral("scriptFileCount")] = scriptFiles.size();

    QJsonArray artifactPathsArr;
    QJsonObject artifactChecksums;
    auto appendArtifact = [&](const QString& path) {
        if (!QFileInfo::exists(path))
            return;
        const QString relative = manifestRelativePath(outputDir, path);
        const QString checksum = DSLCompilerInternal::sha256ForFile(path);
        if (relative.isEmpty() || QDir::isAbsolutePath(relative) || hasParentTraversal(relative)
                || checksum.isEmpty()) {
            return;
        }
        artifactPathsArr.append(relative);
        artifactChecksums[relative] = checksum;
    };
    appendArtifact(codeFile);
    appendArtifact(profileFile);
    appendArtifact(pointsFile);
    const QString listPath = DSLCompilerInternal::outputSidecarFileForSource(
        mainScriptFile, outputDir, QStringLiteral(".list"));
    appendArtifact(listPath);
    const QString typPath = DSLCompilerInternal::outputSidecarFileForSource(
        mainScriptFile, outputDir, QStringLiteral(".typ"));
    appendArtifact(typPath);
    const QString reportPath = DSLCompilerInternal::outputSidecarFileForSource(
        mainScriptFile, outputDir, QStringLiteral(".rep"));
    appendArtifact(reportPath);
    const QString codeRelative = manifestRelativePath(outputDir, codeFile);
    const QString profileRelative = manifestRelativePath(outputDir, profileFile);
    const QString pointsRelative = manifestRelativePath(outputDir, pointsFile);
    const QString codeChecksum = DSLCompilerInternal::sha256ForFile(codeFile);
    const QString profileChecksum = DSLCompilerInternal::sha256ForFile(profileFile);
    const QString pointsChecksum = DSLCompilerInternal::sha256ForFile(pointsFile);
    if (!artifactPathsArr.contains(QJsonValue(codeRelative))
            || !artifactPathsArr.contains(QJsonValue(profileRelative))
            || !artifactPathsArr.contains(QJsonValue(pointsRelative))
            || codeChecksum.isEmpty() || profileChecksum.isEmpty() || pointsChecksum.isEmpty()) {
        return {};
    }
    manifest[QStringLiteral("artifactPaths")] = artifactPathsArr;
    manifest[QStringLiteral("artifactChecksums")] = artifactChecksums;
    manifest[QStringLiteral("codePath")] = codeRelative;
    manifest[QStringLiteral("codeChecksum")] = codeChecksum;
    manifest[QStringLiteral("runtimePointsPath")] = pointsRelative;
    manifest[QStringLiteral("runtimePointsChecksum")] = pointsChecksum;
    manifest[QStringLiteral("downloadProfilePath")] = profileRelative;
    manifest[QStringLiteral("downloadProfileChecksum")] = profileChecksum;
    manifest[QStringLiteral("runtimeManifestPath")] = QStringLiteral("runtime_manifest.json");

    manifest[QStringLiteral("generatedAt")] = QDateTime::currentDateTime().toString(Qt::ISODate);
    manifest[QStringLiteral("pointCount")] = pointCount;
    manifest[QStringLiteral("parameterCount")] = parameterCount;

    manifest[QStringLiteral("complete")] = true;

    const QString filePath = QDir(outputDir).absoluteFilePath(
        QStringLiteral("runtime_manifest.json"));
    QSaveFile file(filePath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        qWarning() << "[DSLCompilerInterface] Failed to write" << filePath;
        return {};
    }
    const QByteArray json = QJsonDocument(manifest).toJson(QJsonDocument::Indented);
    if (file.write(json) != json.size() || !file.commit()) {
        qWarning() << "[DSLCompilerInterface] Failed to commit" << filePath;
        return {};
    }

    QFile verify(filePath);
    if (!verify.open(QIODevice::ReadOnly | QIODevice::Text))
        return {};
    QJsonParseError parseError;
    const QJsonDocument committed = QJsonDocument::fromJson(verify.readAll(), &parseError);
    if (parseError.error != QJsonParseError::NoError || !committed.isObject()
            || !committed.object().value(QStringLiteral("complete")).toBool(false)
            || committed.object().value(QStringLiteral("generationId")).toString() != generationId)
        return {};
    const QJsonObject committedObject = committed.object();
    const QStringList mandatoryManifestPaths = {
        QStringLiteral("codePath"),
        QStringLiteral("downloadProfilePath"),
        QStringLiteral("runtimePointsPath")
    };
    for (const QString& key : mandatoryManifestPaths) {
        if (!isSafeManifestRelativePath(committedObject.value(key).toString()))
            return {};
    }
    const QJsonArray committedArtifacts = committedObject.value(QStringLiteral("artifactPaths")).toArray();
    if (committedArtifacts.isEmpty())
        return {};
    for (const QJsonValue& value : committedArtifacts) {
        if (!isSafeManifestRelativePath(value.toString()))
            return {};
    }
    const QStringList sourcePathKeys = {
        QStringLiteral("mainScriptPath"), QStringLiteral("dslScriptPath")
    };
    for (const QString& key : sourcePathKeys) {
        if (!isSafeManifestRelativePath(committedObject.value(key).toString()))
            return {};
    }
    const QJsonArray committedScripts = committedObject.value(QStringLiteral("scriptFiles")).toArray();
    for (const QJsonValue& value : committedScripts) {
        if (!isSafeManifestRelativePath(value.toString()))
            return {};
    }

    CompileArtifact artifact;
    artifact.type = QString::fromLatin1(CompileArtifactType::RuntimeManifest);
    artifact.path = filePath;
    artifact.format = QStringLiteral("json");
    artifact.checksum = DSLCompilerInternal::sha256ForFile(filePath);
    return artifact;
}
