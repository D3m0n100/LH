QString projectRelativePath(const QString& projectPath, const QString& absolutePath)
{
    return QDir(projectPath).relativeFilePath(QFileInfo(absolutePath).absoluteFilePath());
}

QString profileSourcePath(const QString& projectPath, const ProjectRuntimeConfig& config)
{
    QString configured;
    const QStringList keys = {
        QStringLiteral("downloadProfileSourcePath"),
        QStringLiteral("profileSourcePath"),
        QStringLiteral("sourceProfilePath"),
        QStringLiteral("downloadProfilePath"),
        QStringLiteral("profileJsonPath"),
        QStringLiteral("profilePath")
    };
    for (const QString& key : keys) {
        configured = config.downloadArtifact.metadata.value(key).toString().trimmed();
        const QString normalized = QDir::fromNativeSeparators(configured);
        if ((normalized.startsWith(QStringLiteral("generations/"))
             || normalized.contains(QStringLiteral("/generations/")))
                && normalized.endsWith(QStringLiteral("/download_profile.json"))) {
            configured.clear();
            continue;
        }
        if (!configured.isEmpty())
            break;
    }
    if (configured.isEmpty())
        return QString();
    if (QFileInfo(configured).isRelative())
        return QDir(projectPath).absoluteFilePath(configured);
    return QFileInfo(configured).absoluteFilePath();
}

